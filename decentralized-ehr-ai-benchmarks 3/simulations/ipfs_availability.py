#!/usr/bin/env python3
"""
IPFS availability under node failure (Reviewer 2, comment 1; manuscript Section 4.2).

Monte-Carlo simulation of a 20-node IPFS network. An encrypted record bundle is retrievable if at
least one node that stores it is online. Storage strategies:
  S1  origin only (unpinned, single local node)
  S2  origin + external pinning service (modelled as one extra independent provider whose
      availability A_SERVICE is an ASSUMPTION taken from a provider SLA, not a measurement)
  S3  IPFS Cluster pinning with replication factor k in {2, 3, 5} on distinct random nodes
  S4  IPFS Cluster pinning, k = 3, rack-aware placement (one replica per failure domain)
Failure models:
  F1  independent: each node offline with probability f
  F2  exact fraction: exactly round(f*N) nodes offline, chosen uniformly
  F3  correlated: 4 failure domains (racks/sites) of 5 nodes; a whole domain fails with
      probability f/2, and surviving nodes additionally fail independently with probability f/2
Analytical cross-checks: F1 -> 1 - f^k ; F2 -> 1 - C(m,k)/C(N,k), m = round(fN).
Outputs: logs/ipfs_availability.{csv,md,png}
"""
import csv, math, os, sys, time, platform
import numpy as np

N_NODES, DOMAINS, TRIALS, SEED = 20, 4, 100_000, 2026
FAIL_RATES = [0.10, 0.20, 0.30, 0.40, 0.50]
A_SERVICE = 0.999  # assumption: SLA-level availability of an external pinning provider
OUT = os.path.join(os.path.dirname(__file__), "..", "logs")


def offline_mask(rng, model, f):
    if model == "F1":
        return rng.random((TRIALS, N_NODES)) < f
    if model == "F2":
        m = int(round(f * N_NODES))
        idx = np.argsort(rng.random((TRIALS, N_NODES)), axis=1)[:, :m]
        mask = np.zeros((TRIALS, N_NODES), dtype=bool)
        np.put_along_axis(mask, idx, True, axis=1)
        return mask
    if model == "F3":
        dom_fail = rng.random((TRIALS, DOMAINS)) < f / 2
        per_node = np.repeat(dom_fail, N_NODES // DOMAINS, axis=1)
        return per_node | (rng.random((TRIALS, N_NODES)) < f / 2)
    raise ValueError(model)


def placement(rng, k, rack_aware=False):
    if rack_aware:  # one replica in each of k distinct domains
        doms = np.argsort(rng.random((TRIALS, DOMAINS)), axis=1)[:, :k]
        offs = rng.integers(0, N_NODES // DOMAINS, size=(TRIALS, k))
        return doms * (N_NODES // DOMAINS) + offs
    return np.argsort(rng.random((TRIALS, N_NODES)), axis=1)[:, :k]


def available(mask, nodes):
    return (~np.take_along_axis(mask, nodes, axis=1)).any(axis=1)


def wilson(p, n, z=1.96):
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def main():
    rng = np.random.default_rng(SEED)
    rows, t0 = [], time.time()
    for model in ["F1", "F2", "F3"]:
        for f in FAIL_RATES:
            mask = offline_mask(rng, model, f)
            origin = np.zeros((TRIALS, 1), dtype=int)  # node 0 is the uploader
            strategies = {
                "S1 origin only (unpinned)": available(mask, origin),
                "S2 origin + pinning service (assumed A=0.999)": available(mask, origin) | (rng.random(TRIALS) < A_SERVICE),
            }
            for k in (2, 3, 5):
                strategies[f"S3 cluster pinning k={k}"] = available(mask, placement(rng, k))
            strategies["S4 cluster pinning k=3 rack-aware"] = available(mask, placement(rng, 3, rack_aware=True))
            for name, ok in strategies.items():
                p = float(ok.mean())
                lo, hi = wilson(p, TRIALS)
                k = 1 if name.startswith("S1") else (int(name.split("k=")[1][0]) if "k=" in name else None)
                if model == "F1" and k and "S2" not in name:
                    analytic = 1 - f ** k
                elif model == "F2" and k and "S2" not in name and "rack" not in name:
                    m = int(round(f * N_NODES))
                    analytic = 1 - (math.comb(m, k) / math.comb(N_NODES, k) if k <= m else 0.0)
                else:
                    analytic = None
                rows.append(dict(model=model, fail_rate=f, strategy=name, availability=p, ci_low=lo, ci_high=hi,
                                 analytic=analytic, trials=TRIALS))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "ipfs_availability.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)

    lines = ["# IPFS availability simulation (auto-generated by simulations/ipfs_availability.py)", "",
             f"Generated: {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}  ",
             f"Python {platform.python_version()}, NumPy {np.__version__}; nodes={N_NODES}, failure domains={DOMAINS}, "
             f"trials per cell={TRIALS:,}, seed={SEED}; runtime {time.time() - t0:.1f} s  ",
             f"S2 uses an ASSUMED external-provider availability of {A_SERVICE} (not measured).", "",
             "Failure models: F1 independent node failures; F2 exactly round(f*N) nodes offline; "
             "F3 correlated (domain outage prob f/2 + independent node failure f/2).", ""]
    for model in ["F1", "F2", "F3"]:
        lines += [f"## {model}", "", "| Strategy | " + " | ".join(f"f={f:.0%}" for f in FAIL_RATES) + " |",
                  "|---|" + "---|" * len(FAIL_RATES)]
        for name in dict.fromkeys(r["strategy"] for r in rows):
            cells = []
            for f in FAIL_RATES:
                r = next(x for x in rows if x["model"] == model and x["fail_rate"] == f and x["strategy"] == name)
                cell = f"{100 * r['availability']:.2f}%"
                if r["analytic"] is not None:
                    cell += f" (analytic {100 * r['analytic']:.2f}%)"
                cells.append(cell)
            lines.append(f"| {name} | " + " | ".join(cells) + " |")
        lines.append("")
    lines += ["95% Wilson intervals are in ipfs_availability.csv (half-width <= 0.31 percentage points at 100,000 trials).", ""]
    with open(os.path.join(OUT, "ipfs_availability.md"), "w") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(7, 4.2), dpi=150)
        styles = {"S1 origin only (unpinned)": ("#9aa0a6", "o"), "S3 cluster pinning k=2": ("#7fb3d5", "s"),
                  "S3 cluster pinning k=3": ("#2e86c1", "D"), "S3 cluster pinning k=5": ("#1b4f72", "^"),
                  "S4 cluster pinning k=3 rack-aware": ("#d35400", "v")}
        for name, (col, mk) in styles.items():
            ys = [100 * next(x for x in rows if x["model"] == "F3" and x["fail_rate"] == f and x["strategy"] == name)["availability"] for f in FAIL_RATES]
            ax.plot([100 * f for f in FAIL_RATES], ys, marker=mk, color=col, label=name.replace("S3 ", "").replace("S4 ", "").replace("S1 ", ""))
        ax.set_xlabel("Failure rate f (%)"); ax.set_ylabel("Retrieval availability (%)")
        ax.set_title("IPFS bundle availability, 20 nodes, correlated failures (F3)", fontsize=10)
        ax.grid(alpha=0.3); ax.legend(fontsize=8, frameon=False)
        fig.tight_layout(); fig.savefig(os.path.join(OUT, "ipfs_availability.png"))
    except Exception as e:  # plotting is optional
        print("plot skipped:", e, file=sys.stderr)


if __name__ == "__main__":
    main()
