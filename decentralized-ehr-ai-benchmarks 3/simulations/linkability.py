#!/usr/bin/env python3
"""
Recipient-address linkability under static vs stealth addressing (Reviewer 2, comment 2;
manuscript Section 5.3).

Model: P patients issue E access grants to C clinicians (clinician popularity ~ Zipf(s=1.1)).
A passive chain observer sees, for each grant, the patient address, the recipient address and the
block time. Two recipient-address policies:
  static   each clinician always uses one address
  stealth  every grant uses a fresh ERC-5564 stealth address (lib/stealth.js; addresses generated
           by that code are unique — see offchain-tests/stealth.test.js)
Adversaries:
  A1 address clustering: two grants belong to the same clinician iff same recipient address
  A2 A1 + patient/time heuristic: additionally links grants issued by the same patient within
     24 h (e.g. a referral burst), guessing they go to the same clinician
Metrics over all pairs of grants: pairwise linkage precision/recall (the "same clinician" relation),
and per-grant anonymity-set size (number of clinicians the observer cannot exclude).
What is NOT modelled: patient-address rotation (patients keep one address per record namespace),
network-level (IP) correlation, and clinicians funding stealth addresses from a known wallet
(mitigated in the prototype because AI commitments are relayed, see appendDiagnosticAI).
Outputs: logs/linkability.{md,csv}
"""
import csv, os, time, platform
import numpy as np

SEED, C, P, E, DAYS = 2026, 20, 200, 5000, 30
OUT = os.path.join(os.path.dirname(__file__), "..", "logs")


def fmt(x):
    return "n/a (no pairs linked)" if x != x else f"{x:.4f}"


def pair_metrics(true_ids, pred_clusters):
    """Pairwise precision/recall of 'same clinician' using counting formulas (O(E))."""
    def pairs(labels):
        _, cnt = np.unique(labels, return_counts=True)
        return int((cnt * (cnt - 1) // 2).sum())
    joint = np.array([f"{a}|{b}" for a, b in zip(true_ids, pred_clusters)])
    tp = pairs(joint); pred = pairs(pred_clusters); true = pairs(true_ids)
    return (tp / pred if pred else float("nan")), (tp / true if true else float("nan")), tp, pred, true


def union_find_clusters(n, edges):
    parent = list(range(n))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for a, b in edges:
        ra, rb = find(a), find(b)
        if ra != rb: parent[ra] = rb
    return np.array([find(i) for i in range(n)])


def main():
    rng = np.random.default_rng(SEED)
    w = 1 / np.arange(1, C + 1) ** 1.1; w /= w.sum()
    clin = rng.choice(C, size=E, p=w)
    patient = rng.integers(0, P, size=E)
    t = np.sort(rng.uniform(0, DAYS * 24, size=E))  # hours
    H_prior = float(-(w * np.log2(w)).sum())
    rows = []
    for policy in ["static", "stealth"]:
        addr = clin.copy() if policy == "static" else np.arange(E) + C  # unique per grant
        # A1: address clustering
        p1, r1, *_ = pair_metrics(clin, addr)
        anon1 = 1 if policy == "static" else C
        rows.append(dict(policy=policy, adversary="A1 address clustering", precision=p1, recall=r1,
                         anonymity_set=anon1, residual_entropy_bits=0.0 if policy == "static" else H_prior))
        # A2: + same patient within 24 h
        edges = []
        order = np.lexsort((t, patient))
        for i in range(1, E):
            a, b = order[i - 1], order[i]
            if patient[a] == patient[b] and abs(t[a] - t[b]) <= 24:
                edges.append((a, b))
        # address-based edges
        _, first = np.unique(addr, return_index=True)
        rep = {a: f for a, f in zip(np.unique(addr), first)}
        edges += [(i, rep[addr[i]]) for i in range(E)]
        clusters = union_find_clusters(E, edges)
        p2, r2, *_ = pair_metrics(clin, clusters)
        rows.append(dict(policy=policy, adversary="A2 address + patient/24h heuristic", precision=p2, recall=r2,
                         anonymity_set=None, residual_entropy_bits=None))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "linkability.csv"), "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); wr.writeheader(); wr.writerows(rows)
    lines = ["# Recipient linkability simulation (auto-generated by simulations/linkability.py)", "",
             f"Generated: {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}  ",
             f"Python {platform.python_version()}, NumPy {np.__version__}; clinicians={C}, patients={P}, grants={E}, "
             f"period={DAYS} days, Zipf s=1.1, seed={SEED}  ",
             f"Prior entropy of the recipient clinician H(C) = {H_prior:.3f} bits", "",
             "| Address policy | Adversary | Pairwise linkage precision | Pairwise linkage recall | Anonymity set per grant | Residual uncertainty (bits) |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        anon = r["anonymity_set"] if r["anonymity_set"] is not None else "–"
        ent = "%.3f" % r["residual_entropy_bits"] if r["residual_entropy_bits"] is not None else "–"
        lines.append(f"| {r['policy']} | {r['adversary']} | {fmt(r['precision'])} | {fmt(r['recall'])} | {anon} | {ent} |")
    lines += ["", "Recall = fraction of truly same-clinician grant pairs the observer links; precision = fraction of linked pairs that are correct.",
              "Residual uncertainty is the observer's entropy about the recipient of a single grant from the recipient address alone.", ""]
    with open(os.path.join(OUT, "linkability.md"), "w") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
