"use strict";
/**
 * IPFS upload/download benchmark against a REAL Kubo node (manuscript Table 6, IPFS columns).
 *   ipfs daemon &            # Kubo, local node
 *   node scripts/benchmark-ipfs.js
 * Env: IPFS_API (default http://127.0.0.1:5001), TRIALS (50), SIZES_KB (as crypto benchmark)
 * Each trial uploads a fresh random encrypted bundle (no dedup), pins it, then cats it back.
 * Report the topology (local vs remote peers), pinning and cache state with the results.
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const crypto = require("crypto");
const C = require("../lib/ehrCrypto");
const { KuboStore } = require("../lib/ipfsStore");

const TRIALS = Number(process.env.TRIALS || 50);
const SIZES_KB = (process.env.SIZES_KB || "512,1024,10240,51200,102400,512000").split(",").map(Number);
const summary = (a) => { const n = a.length, m = a.reduce((x, y) => x + y, 0) / n; const sd = Math.sqrt(a.reduce((s, x) => s + (x - m) ** 2, 0) / (n - 1)); return { mean: m, ci: (n >= 30 ? 1.96 : 2.1) * sd / Math.sqrt(n) }; };

(async () => {
  const store = new KuboStore();
  const version = await store.version().catch(() => null);
  if (!version) { console.error("No Kubo node reachable at", store.api, "- start `ipfs daemon` first."); process.exit(1); }
  const rows = [];
  for (const kb of SIZES_KB) {
    const up = [], down = [];
    for (let i = 0; i < TRIALS; i++) {
      const { bundle } = C.encryptPayload(crypto.randomBytes(kb * 1024));
      let t = process.hrtime.bigint();
      const cid = await store.add(bundle);
      up.push(Number(process.hrtime.bigint() - t) / 1e9);
      t = process.hrtime.bigint();
      const back = await store.cat(cid);
      down.push(Number(process.hrtime.bigint() - t) / 1e9);
      if (!back.equals(bundle)) throw new Error("IPFS round-trip mismatch");
    }
    rows.push({ kb, up: summary(up), down: summary(down) });
    console.log(`${kb} KB: upload ${rows.at(-1).up.mean.toFixed(3)} s, download ${rows.at(-1).down.mean.toFixed(3)} s`);
  }
  const dir = path.join(__dirname, "..", "logs"); fs.mkdirSync(dir, { recursive: true });
  const f = (s) => `${s.mean.toFixed(3)} ± ${s.ci.toFixed(3)}`;
  fs.writeFileSync(path.join(dir, "ipfs_benchmark.md"), [
    "# IPFS benchmark (auto-generated by scripts/benchmark-ipfs.js)", "",
    `Generated: ${new Date().toISOString()}  `, `Kubo ${version} at ${store.api}; host ${os.cpus()[0].model}, ${os.type()} ${os.arch()}  `,
    `Trials: ${TRIALS}; add with cid-version=1, raw-leaves, pin=true; cat from the same node (local, warm).`, "",
    "| Payload | IPFS upload (s) | IPFS download (s) |", "|---|---|---|",
    ...rows.map((r) => `| ${r.kb >= 1024 ? r.kb / 1024 + " MB" : r.kb + " KB"} | ${f(r.up)} | ${f(r.down)} |`), "",
  ].join("\n"));
})();
