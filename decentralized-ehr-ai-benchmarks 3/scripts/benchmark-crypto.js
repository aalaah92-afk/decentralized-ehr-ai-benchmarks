"use strict";
/**
 * Off-chain cryptographic micro-benchmarks (manuscript Table 6, columns AES-256-GCM encrypt /
 * decrypt, plus ECIES wrap/unwrap and SHA-256 digests used in Table 7).
 *   node scripts/benchmark-crypto.js
 * Env: TRIALS (default 50), SIZES_KB (default "512,1024,10240,51200,102400,512000")
 * Outputs: logs/crypto_benchmark.csv, logs/crypto_benchmark.md (with host hardware)
 * Timing boundary: in-memory buffers, single thread, excludes disk I/O and network.
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const crypto = require("crypto");
const C = require("../lib/ehrCrypto");

const TRIALS = Number(process.env.TRIALS || 50);
const SIZES_KB = (process.env.SIZES_KB || "512,1024,10240,51200,102400,512000").split(",").map(Number);
// two-sided 95% t critical values
const T95 = (df) => ({ 1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 9: 2.262, 19: 2.093, 29: 2.045, 49: 2.010, 99: 1.984 }[df] || 1.96);
const summary = (a) => {
  const n = a.length, mean = a.reduce((x, y) => x + y, 0) / n;
  const sd = Math.sqrt(a.reduce((s, x) => s + (x - mean) ** 2, 0) / (n - 1));
  return { mean, ci: (T95(n - 1) * sd) / Math.sqrt(n) };
};
const time = (fn) => { const t = process.hrtime.bigint(); const r = fn(); return [Number(process.hrtime.bigint() - t) / 1e9, r]; };

const clinician = crypto.createECDH("secp256k1"); clinician.generateKeys();
const ctx = { recordId: "0x" + "ab".repeat(32), version: 1, clinicianAddress: "0x" + "cd".repeat(20) };

const rows = [];
for (const kb of SIZES_KB) {
  const P = crypto.randomBytes(kb * 1024);
  const m = { enc: [], dec: [], wrap: [], unwrap: [], hp: [], hc: [] };
  for (let i = 0; i < TRIALS + 2; i++) {
    const [tEnc, e] = time(() => C.encryptPayload(P));
    const cid = C.cidV1Raw(e.bundle.subarray(0, 1024)); // CID value only needed as bytes for H_C
    const [tHc] = time(() => C.ciphertextDigest(e.bundle, cid));
    const [tHp] = time(() => C.sha256(P));
    const [tWrap, wk] = time(() => C.wrapKey(e.key, clinician.getPublicKey(), ctx));
    const [tUnwrap, K] = time(() => C.unwrapKey(wk, clinician.getPrivateKey(), ctx));
    const [tDec, out] = time(() => C.decryptBundle(e.bundle, K));
    if (!out.equals(P)) throw new Error("round-trip failure");
    if (i < 2) continue; // warm-up
    m.enc.push(tEnc); m.dec.push(tDec); m.wrap.push(tWrap); m.unwrap.push(tUnwrap); m.hp.push(tHp); m.hc.push(tHc);
  }
  const row = { sizeKB: kb };
  for (const k of Object.keys(m)) row[k] = summary(m[k]);
  rows.push(row);
  console.log(`${kb} KB: enc ${row.enc.mean.toFixed(4)}±${row.enc.ci.toFixed(4)} s, dec ${row.dec.mean.toFixed(4)}±${row.dec.ci.toFixed(4)} s`);
}

const host = `${os.cpus()[0].model} x${os.cpus().length}, ${(os.totalmem() / 2 ** 30).toFixed(1)} GiB RAM, ${os.type()} ${os.release()} ${os.arch()}, Node ${process.version}, OpenSSL ${process.versions.openssl}`;
const dir = path.join(__dirname, "..", "logs");
fs.mkdirSync(dir, { recursive: true });
const f = (s) => `${s.mean.toFixed(4)} ± ${s.ci.toFixed(4)}`;
fs.writeFileSync(path.join(dir, "crypto_benchmark.csv"),
  ["size_kb,metric,mean_s,ci95_s", ...rows.flatMap((r) => ["enc", "dec", "wrap", "unwrap", "hp", "hc"].map((k) => `${r.sizeKB},${k},${r[k].mean},${r[k].ci}`))].join("\n") + "\n");
fs.writeFileSync(path.join(dir, "crypto_benchmark.md"), [
  "# Cryptographic micro-benchmark (auto-generated by scripts/benchmark-crypto.js)", "",
  `Generated: ${new Date().toISOString()}  `, `Host: ${host}  `, `Trials per size: ${TRIALS} (+2 warm-up discarded); mean ± 95% CI (t-distribution)`, "",
  "| Payload | AES-256-GCM encrypt (s) | AES-256-GCM decrypt (s) | SHA-256 H_P (s) | SHA-256 H_C (s) | ECIES wrap (s) | ECIES unwrap (s) |",
  "|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.sizeKB >= 1024 ? r.sizeKB / 1024 + " MB" : r.sizeKB + " KB"} | ${f(r.enc)} | ${f(r.dec)} | ${f(r.hp)} | ${f(r.hc)} | ${f(r.wrap)} | ${f(r.unwrap)} |`),
  "", "Timing boundary: in-memory, single-threaded Node.js crypto (OpenSSL); excludes file I/O and network.",
].join("\n") + "\n");
