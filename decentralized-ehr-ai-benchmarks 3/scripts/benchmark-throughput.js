"use strict";
/**
 * Concurrent-load benchmark (Reviewer 4 c.6): throughput, failed-transaction rate, txs/block.
 *   npx hardhat run scripts/benchmark-throughput.js
 * Env: CONCURRENCY (default "10,50,100,500")
 * Boundary: single-process Hardhat EDR node with manual block production (30M gas limit).
 * The result measures local execution capacity of this contract, NOT public-network,
 * consortium or Layer-2 throughput.
 */
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");
const H = require("../test/helpers");

const LEVELS = (process.env.CONCURRENCY || "10,50,100,500").split(",").map(Number);

async function main() {
  const [governance, , funder] = await ethers.getSigners();
  const registry = await (await ethers.getContractFactory("EHRRegistry")).deploy(governance.address);
  await registry.waitForDeployment();
  const store = new H.LocalCASStore();
  const maxN = Math.max(...LEVELS);

  console.log(`preparing ${maxN} patients with one registered record each...`);
  const patients = [];
  for (let i = 0; i < maxN; i++) {
    const p = await H.fundedWallet(funder, "1");
    const recordId = H.bytes32(`tp-${i}`);
    const v = await H.prepareRecordVersion({ registry, store, patient: p, recordId, version: 1, plaintext: H.randomPayload(256) });
    await (await registry.connect(p).registerRecord(v.input, v.signature)).wait();
    patients.push({ p, recordId, key: v.key });
  }

  const results = [];
  for (const n of LEVELS) {
    await network.provider.send("evm_setAutomine", [false]);
    const clinicians = Array.from({ length: n }, () => ethers.Wallet.createRandom());
    const t0 = process.hrtime.bigint();
    const settled = await Promise.allSettled(patients.slice(0, n).map(({ p, recordId, key }, i) =>
      registry.connect(p).grantAccess(recordId, clinicians[i].address, false, H.wrapFor(key, clinicians[i], recordId, 1), { gasLimit: 300000 })));
    const sent = settled.filter((s) => s.status === "fulfilled").map((s) => s.value);
    let blocks = 0;
    while ((await network.provider.send("eth_getBlockByNumber", ["pending", false])).transactions.length > 0) {
      await network.provider.send("evm_mine"); blocks++;
      if (blocks > 1000) break;
    }
    const receipts = await Promise.all(sent.map((tx) => ethers.provider.getTransactionReceipt(tx.hash)));
    const seconds = Number(process.hrtime.bigint() - t0) / 1e9;
    const ok = receipts.filter((r) => r && r.status === 1).length;
    const failed = n - ok;
    results.push({ n, ok, failed, failRate: (100 * failed) / n, blocks, seconds, tps: ok / seconds });
    await network.provider.send("evm_setAutomine", [true]);
    console.log(`concurrency ${n}: ${ok}/${n} confirmed in ${blocks} block(s), ${seconds.toFixed(3)} s, ${(ok / seconds).toFixed(1)} tx/s, failed ${failed}`);
  }

  const dir = path.join(__dirname, "..", "logs"); fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "throughput_benchmark.md"), [
    "# Concurrent grantAccess() load (auto-generated by scripts/benchmark-throughput.js)", "",
    `Generated: ${new Date().toISOString()}  `, `Network: ${network.name} (single-process Hardhat EDR, manual mining, 30M block gas limit)`, "",
    "| Concurrent clients | Confirmed | Failed | Failure rate (%) | Blocks | Wall time (s) | Throughput (tx/s) |", "|---|---|---|---|---|---|---|",
    ...results.map((r) => `| ${r.n} | ${r.ok} | ${r.failed} | ${r.failRate.toFixed(2)} | ${r.blocks} | ${r.seconds.toFixed(3)} | ${r.tps.toFixed(1)} |`), "",
    "Boundary: local execution capacity only; not representative of Sepolia, consortium or Layer-2 networks.",
  ].join("\n"));
}
main().catch((e) => { console.error(e); process.exitCode = 1; });
