#!/usr/bin/env python3
"""
Deterministic patient-level 80/10/10 split of NIH ChestX-ray14 (manuscript Section 3.6).

  python ai/split_patients.py --data-entry /path/to/Data_Entry_2017.csv --out ai/manifests

Writes train/val/test manifests (Image Index, Patient ID, 14 binary labels), verifies zero patient
overlap, and prints integer image/patient/positive counts per split (logs/split_summary.md).
"""
import argparse, os, time
import numpy as np
import pandas as pd
from common import LABELS, SPLIT_SEED


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-entry", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "manifests"))
    ap.add_argument("--log", default=os.path.join(os.path.dirname(__file__), "..", "logs", "split_summary.md"))
    ap.add_argument("--seed", type=int, default=SPLIT_SEED)
    a = ap.parse_args()

    df = pd.read_csv(a.data_entry)
    for lab in LABELS:
        df[lab] = df["Finding Labels"].str.split("|").apply(lambda xs, l=lab: int(l in xs))
    patients = np.sort(df["Patient ID"].unique())
    rng = np.random.default_rng(a.seed)
    perm = rng.permutation(patients)
    n = len(perm); n_tr = int(round(0.8 * n)); n_va = int(round(0.1 * n))
    groups = {"train": set(perm[:n_tr]), "val": set(perm[n_tr:n_tr + n_va]), "test": set(perm[n_tr + n_va:])}
    assert not (groups["train"] & groups["val"]) and not (groups["train"] & groups["test"]) and not (groups["val"] & groups["test"])

    os.makedirs(a.out, exist_ok=True)
    lines = ["# Patient-level split (auto-generated by ai/split_patients.py)", "",
             f"Generated: {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}; seed={a.seed}; source={os.path.basename(a.data_entry)}", "",
             "| Split | Patients | Images | " + " | ".join(LABELS) + " |", "|---|---|---|" + "---|" * len(LABELS)]
    for name, ids in groups.items():
        part = df[df["Patient ID"].isin(ids)][["Image Index", "Patient ID"] + LABELS].sort_values("Image Index")
        part.to_csv(os.path.join(a.out, f"{name}.csv"), index=False)
        lines.append(f"| {name} | {len(ids)} | {len(part)} | " + " | ".join(str(int(part[l].sum())) for l in LABELS) + " |")
    lines += ["", "Patient overlap between splits: 0 (asserted)", ""]
    os.makedirs(os.path.dirname(a.log), exist_ok=True)
    open(a.log, "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
