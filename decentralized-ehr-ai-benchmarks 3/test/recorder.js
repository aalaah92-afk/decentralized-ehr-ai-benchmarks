"use strict";
/**
 * Records EXPECTED vs OBSERVED outcomes of every adversarial test case and writes them to
 * logs/security_test_matrix.{md,json}. The observed column is produced from the actual
 * execution result (decoded custom error / emitted event), never typed by hand.
 */
const fs = require("fs");
const path = require("path");

const rows = [];

function decodeRevert(registry, err) {
  const candidates = [err?.data, err?.error?.data, err?.info?.error?.data, err?.data?.data];
  for (const d of candidates) {
    if (typeof d === "string" && d.startsWith("0x") && d.length >= 10) {
      try { const parsed = registry.interface.parseError(d); if (parsed) return parsed.name; } catch { /* continue */ }
    }
  }
  const m = /custom error '([A-Za-z0-9_]+)\(/.exec(err?.message || "") || /reverted with reason string '([^']+)'/.exec(err?.message || "");
  return m ? m[1] : `UNDECODED(${(err?.message || String(err)).slice(0, 80)})`;
}

/** Executes fn (tx send / call). Returns "SUCCESS" or "REVERT:<ErrorName>". */
async function outcomeOf(registry, fn) {
  try {
    const r = await fn();
    if (r && typeof r.wait === "function") await r.wait();
    return "SUCCESS";
  } catch (e) {
    return `REVERT:${decodeRevert(registry, e)}`;
  }
}

function add(row) { rows.push({ ...row, pass: row.expected === row.observed }); }

function write() {
  const dir = path.join(__dirname, "..", "logs");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "security_test_matrix.json"), JSON.stringify({ generatedAt: new Date().toISOString(), rows }, null, 2));
  const lines = [
    "# Adversarial security test matrix (auto-generated by `npx hardhat test`)",
    "",
    `Generated: ${new Date().toISOString()}  `,
    `Cases: ${rows.length}, passed: ${rows.filter((r) => r.pass).length}`,
    "",
    "| ID | Attack vector | Adversarial action | Expected | Observed | Pass |",
    "|---|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.id} | ${r.vector} | ${r.action} | ${r.expected} | ${r.observed} | ${r.pass ? "yes" : "NO"} |`),
    "",
  ];
  fs.writeFileSync(path.join(dir, "security_test_matrix.md"), lines.join("\n"));
}

module.exports = { outcomeOf, decodeRevert, add, write, rows };
